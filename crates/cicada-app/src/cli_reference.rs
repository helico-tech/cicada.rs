//! The help of the command line as a reference, `docs/reference/cli.md`: the help of the plain `cicada` binary and of
//! every command and subcommand, found by walking the tree with `get_subcommands`, and the help of `serve` and `worker`
//! as an `App` with one type, called `myapp`, prints it. Each page is rendered with a fixed name, so the reference does
//! not depend on how the test binary is called. The test fails when the file differs from what the code renders, and
//! rewrites it when the tests run with `CICADA_UPDATE_CLI=true`. The reference holds the help with the terminal UI, so
//! this module is built only with the feature `tui`: `cargo test --workspace` runs it, `cargo test -p cicada-app` alone
//! does not, and `cargo test -p cicada-app --features tui` does.

use std::ffi::OsString;
use std::io::Write;
use std::path::Path;
use std::sync::{Arc, Mutex};

use cicada::prelude::*;
use clap::Command;
use serde::{Deserialize, Serialize};

use crate::{App, Env, command};

/// The reference, from the root of the repository.
const REFERENCE: &str = "docs/reference/cli.md";

/// The variable that makes the test rewrite the reference.
const UPDATE: &str = "CICADA_UPDATE_CLI";

/// The words before each page: what the file is and how it is made.
const HEADER: &str = "# The command line

The help of the plain `cicada` binary and of each of its commands, as `--help` prints it, with the terminal UI (the
feature `tui` of `cicada-app`). A binary built from `App` with types has the same commands under its own name, and
`serve` and `worker` too; their help is at the end, for a binary called `myapp`. See [the app guide](../guide/app.md)
for what the commands do.

This file is generated by a test of `cicada-app` (`crates/cicada-app/src/cli_reference.rs`) and checked by it: do not
edit it. When the help changes, run the tests with `CICADA_UPDATE_CLI=true` and commit the file:
`CICADA_UPDATE_CLI=true cargo test --workspace`, or `CICADA_UPDATE_CLI=true cargo test -p cicada-app --features tui`.
";

/// Every command of `tree` as the words that call it, the binary first, depth first in the order of the tree.
fn paths(tree: &Command) -> Vec<Vec<String>> {
    fn walk(command: &Command, path: Vec<String>, out: &mut Vec<Vec<String>>) {
        out.push(path.clone());
        for sub in command.get_subcommands() {
            let mut next = path.clone();
            next.push(sub.get_name().to_owned());
            walk(sub, next, out);
        }
    }
    let mut out = Vec::new();
    walk(tree, vec![tree.get_name().to_owned()], &mut out);
    out
}

/// An output the test reads after the command wrote to it.
#[derive(Clone, Default)]
struct Out(Arc<Mutex<Vec<u8>>>);

impl Write for Out {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(bytes);
        Ok(bytes.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

/// What `app` prints for the words of `path` followed by `--help`; the first word is the name of the binary.
async fn help(app: App, path: &[String]) -> String {
    let out = Out::default();
    let args: Vec<OsString> = path.iter().map(OsString::from).chain([OsString::from("--help")]).collect();
    app.run_with(args, Env::new(), out.clone(), std::future::pending())
        .await
        .unwrap_or_else(|e| panic!("{}: {e}", path.join(" ")));
    String::from_utf8(out.0.lock().unwrap().clone()).unwrap()
}

/// The one type of the binary `myapp`, so that it has `serve` and `worker`.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Probe;

impl ActorRef for Probe {
    const TYPE: &'static str = "probe";
    type Message = ProbeMsg;
}

#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "type")]
enum ProbeMsg {
    Ping,
}

struct ProbeActor;

impl Actor for ProbeActor {
    type Ref = Probe;
    type State = NoState;

    async fn handle(&self, _turn: &mut Turn<Self>, _message: ProbeMsg) -> HandlerResult {
        Ok(())
    }
}

/// The reference as the code renders it.
async fn reference() -> String {
    let mut pages = Vec::new();
    for path in paths(&command::command("cicada", false)) {
        let text = help(App::new(), &path).await;
        pages.push((path.join(" "), text));
    }
    let serve_and_worker = paths(&command::command("myapp", true))
        .into_iter()
        .filter(|path| path.get(1).is_some_and(|word| word == "serve" || word == "worker"));
    for path in serve_and_worker {
        let text = help(App::new().host(ProbeActor), &path).await;
        pages.push((path.join(" "), text));
    }
    let mut out = String::from(HEADER);
    for (title, text) in pages {
        out.push_str(&format!("\n## `{title}`\n\n```text\n{}\n```\n", text.trim_end()));
    }
    out
}

/// The titles of the pages of a reference with their text, by the headings `` ## `…` ``.
fn pages(reference: &str) -> Vec<(&str, &str)> {
    reference.split("\n## `").skip(1).filter_map(|page| page.split_once("`\n")).collect()
}

/// Compares `current` with the file at `path`, or writes it there when `update`. The error names the pages that
/// differ, and says how to rewrite the file.
fn check(current: &str, path: &Path, update: bool) -> Result<(), String> {
    if update {
        std::fs::create_dir_all(path.parent().expect("a folder")).map_err(|e| format!("{}: {e}", path.display()))?;
        std::fs::write(path, current).map_err(|e| format!("{}: {e}", path.display()))?;
        return Ok(());
    }
    let on_disk = std::fs::read_to_string(path).unwrap_or_default();
    if on_disk == current {
        return Ok(());
    }
    let old = pages(&on_disk);
    let new = pages(current);
    let mut changed: Vec<String> = new
        .iter()
        .filter(|page| !old.contains(page))
        .map(|(title, _)| match old.iter().any(|(t, _)| t == title) {
            true => format!("`{title}` changed"),
            false => format!("`{title}` is new"),
        })
        .collect();
    changed.extend(old.iter().filter(|(t, _)| !new.iter().any(|(n, _)| n == t)).map(|(t, _)| format!("`{t}` is gone")));
    if changed.is_empty() {
        changed.push("the text outside the pages changed".to_owned());
    }
    Err(format!(
        "{REFERENCE} is out of date: {}. If the change is meant, rewrite it with {UPDATE}=true and commit it: \
         `{UPDATE}=true cargo test --workspace`, or `{UPDATE}=true cargo test -p cicada-app --features tui` (the \
         reference holds the help with the terminal UI, so the test needs --workspace or --features tui).",
        changed.join(", ")
    ))
}

/// The file of the reference.
fn file() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").join(REFERENCE)
}

#[tokio::test]
async fn the_reference_of_the_command_line_is_current() {
    let update = std::env::var(UPDATE).is_ok_and(|v| v == "true");
    if let Err(e) = check(&reference().await, &file(), update) {
        panic!("{e}");
    }
}

/// Scenario: The name of the test binary.
#[tokio::test]
async fn the_reference_names_cicada_whatever_the_test_binary_is_called() {
    let own = command::program_name(&std::env::args_os().collect::<Vec<_>>());
    assert_ne!(own, "cicada", "the test binary has another name");
    let called_by_its_own_name = help(App::new(), &[own.clone(), "get".into(), "actors".into()]).await;
    assert!(called_by_its_own_name.contains(&format!("Usage: {own} get actors")), "{called_by_its_own_name}");

    let reference = reference().await;
    assert!(reference.contains("Usage: cicada get actors"), "{reference}");
    assert!(reference.contains("Usage: myapp serve"), "{reference}");
    assert!(!reference.contains(&own), "the reference names the test binary {own}");
}

/// Scenario: A subcommand is added. The walk finds every command of the tree, so a new one gets a page.
#[test]
fn the_walk_finds_every_command_of_the_tree() {
    let tree = Command::new("cicada")
        .subcommand(Command::new("get").subcommand(Command::new("actors")).subcommand(Command::new("new")))
        .subcommand(Command::new("health"));
    let found: Vec<String> = paths(&tree).iter().map(|p| p.join(" ")).collect();
    assert_eq!(found, ["cicada", "cicada get", "cicada get actors", "cicada get new", "cicada health"]);
}

/// Scenarios: A flag is added, and a subcommand is added. The error names what changed and how to rewrite the file.
#[test]
fn a_reference_that_differs_names_its_pages_and_how_to_rewrite_it() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("cli.md");
    let old = format!("{HEADER}\n## `cicada get`\n\n```text\nold\n```\n\n## `cicada health`\n\n```text\nsame\n```\n");
    std::fs::write(&path, &old).unwrap();
    assert_eq!(check(&old, &path, false), Ok(()));

    let new =
        old.replace("old", "with --a-new-flag") + "\n## `cicada get new`\n\n```text\nUsage: cicada get new\n```\n";
    let error = check(&new, &path, false).unwrap_err();
    assert!(
        error.starts_with("docs/reference/cli.md is out of date: `cicada get` changed, `cicada get new` is new"),
        "{error}"
    );
    assert!(error.contains("CICADA_UPDATE_CLI=true") && error.contains("--workspace"), "{error}");
    assert!(error.contains("--features tui"), "{error}");

    check(&new, &path, true).unwrap();
    assert_eq!(std::fs::read_to_string(&path).unwrap(), new);
    assert_eq!(check(&new, &path, false), Ok(()));
}
